class operators
{
    public static void main(String []args)
    {
        // modulo operators
        int a = 8;
        int b =  15;
        int c = b%a;
        System.out.println(c);
        // Assignment operators
        int d = 10;
        d += 6 ;
        int e = d*c;
        System.out.println(e);
        System.out.println(273>98 || 98<29);
        System.out.println(273>98 && 98<29);


        // Increment and decrement operators

        int n = 45;
        System.out.println(n);
        n++;
        System.out.println(n);
        System.out.println(n++);
        System.out.println(n);
    }
}